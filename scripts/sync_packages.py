"""Copy the word lists into every package and stamp the version from VERSION everywhere.

Run after changing lists/ or VERSION:  python3 scripts/sync_packages.py
Then: ruby tests, python tests, npm test, and publish (see CONTRIBUTING.md).
"""
import json, os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = lambda *a: os.path.join(ROOT, *a)
version = open(p("VERSION")).read().strip()
assert re.fullmatch(r"\d+\.\d+\.\d+", version), version

def sub(path, pattern, repl):
    text = open(path, encoding="utf-8").read()
    new, n = re.subn(pattern, repl, text, count=1, flags=re.M)
    assert n == 1, f"{path}: pattern not found"
    open(path, "w", encoding="utf-8", newline="\n").write(new)

def read_words(name):
    return [l.split("\t")[1] for l in open(p("lists", name), encoding="utf-8").read().split("\n") if l]

# Ruby (uses lists/ from repo root directly)
sub(p("lib/diceware_polski/version.rb"), r'VERSION = "[^"]+"', f'VERSION = "{version}"')

# Python
for name in ("diceware-pl.txt", "diceware-pl-ogonki.txt"):
    shutil.copyfile(p("lists", name), p("python/src/diceware_polski/lists", name))
sub(p("python/pyproject.toml"), r'^version = "[^"]+"', f'version = "{version}"')
sub(p("python/src/diceware_polski/__init__.py"), r'__version__ = "[^"]+"', f'__version__ = "{version}"')

# JavaScript
plain, ogonki = read_words("diceware-pl.txt"), read_words("diceware-pl-ogonki.txt")
dump = lambda ws: json.dumps(ws, ensure_ascii=False, separators=(",", ":"))
with open(p("js/lists.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts/sync_packages.py from lists/ - do not edit.\n")
    f.write(f"export const PLAIN = Object.freeze({dump(plain)});\n")
    f.write(f"export const OGONKI = Object.freeze({dump(ogonki)});\n")
pkg = json.load(open(p("js/package.json"), encoding="utf-8"))
pkg["version"] = version
open(p("js/package.json"), "w", encoding="utf-8", newline="\n").write(json.dumps(pkg, ensure_ascii=False, indent=2) + "\n")

# Shared files
for d in ("python", "js"):
    for f in ("LICENSE", "LICENSE-LISTS"):
        shutil.copyfile(p(f), p(d, f))
    shutil.copyfile(p("PACKAGE_README.md"), p(d, "README.md"))
print("synced version", version)
